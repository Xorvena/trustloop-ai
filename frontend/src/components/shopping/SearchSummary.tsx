import { AlertTriangle, Info } from "lucide-react";
import { Badge, Card } from "@/components/shared/ui";
import type { SearchResponse } from "@/types";

const REASON_LABEL: Record<string, string> = {
  not_configured: "Gemini is not configured", model_not_found: "Gemini model not found", invalid_api_key: "Gemini rejected the API key",
  permission_denied: "Gemini denied access", rate_limited: "Gemini rate limit reached", upstream_error: "Gemini service error",
  network_error: "Could not reach Gemini", bad_output: "Gemini returned invalid output", contradicted_results: "Gemini contradicted the verified results",
  bad_request: "Gemini rejected the request", unknown_error: "Gemini request failed", unavailable: "Gemini unavailable",
  recently_unavailable: "Gemini was unavailable moments ago (skipped)",
};

/** Always states truthfully who wrote the summary: Gemini (with model) or the built-in template (with the reason). */
export function SourceBadge({ source, model, reason, fallbackModel }: { source: "gemini" | "template" | "heuristic"; model: string | null; reason: string | null; fallbackModel?: boolean }) {
  if (source === "gemini") return <Badge tone="violet">Generated by Gemini{model ? ` · ${model}` : ""}{fallbackModel ? " (fallback model)" : ""}</Badge>;
  return <Badge tone="amber">{source === "heuristic" ? "Rule-based parser" : "Template summary (not AI)"}{reason ? ` · ${REASON_LABEL[reason] ?? reason}` : ""}</Badge>;
}

export function SearchSummary({ res }: { res: SearchResponse }) {
  const fell = res.summary_source === "template" && res.summary_fallback_reason && res.summary_fallback_reason !== "not_configured";
  return (
    <div className="space-y-3">
      <Card className="p-5">
        <div className="mb-2 flex flex-wrap gap-2">
          <SourceBadge source={res.summary_source} model={res.summary_model} reason={res.summary_fallback_reason} fallbackModel={res.summary_used_fallback_model} />
          <Badge tone="slate">Demo catalog</Badge>
        </div>
        <p className="text-sm text-slate-200">{res.summary}</p>
        {fell && <p className="mt-2 flex items-start gap-1 text-xs text-warn"><AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" />{res.summary_fallback_message}</p>}
        <p className="mt-2 text-xs text-slate-500">{res.catalog_notice}</p>
      </Card>
      <Card className="p-4">
        <div className="flex flex-wrap items-center gap-2 text-xs">
          <span className="text-slate-500">Understood as:</span>
          {res.interpreted_as.length ? res.interpreted_as.map((t) => <span key={t} className="rounded-full border border-navy-600 px-2 py-0.5 text-slate-300">{t}</span>) : <span className="text-slate-500">nothing specific</span>}
          <SourceBadge source={res.intent_source} model={res.intent_model} reason={res.intent_fallback_reason} fallbackModel={res.intent_used_fallback_model} />
        </div>
        {res.intent_notes.map((n) => <p key={n} className="mt-1 flex gap-1 text-xs text-slate-500"><Info className="mt-0.5 h-3.5 w-3.5 shrink-0" />{n}</p>)}
        {res.unverifiable_terms.length > 0 && <p className="mt-2 flex items-start gap-1 text-xs text-warn"><AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" />Could not verify against catalog data: {res.unverifiable_terms.join(", ")}. Results do not account for these.</p>}
      </Card>
      {res.provider_status.map((p) => p.ok && !p.message ? (
        <p key={p.provider} className="flex items-center gap-1 text-xs text-slate-500"><Info className="h-3.5 w-3.5" />Also searched demo provider “{p.provider}” ({p.count} products). Demo data, not live retailer inventory.</p>
      ) : (
        <div key={p.provider} role="status" className="flex items-start gap-2 rounded-xl border border-red-500/30 bg-red-500/5 p-3 text-sm text-slate-200">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-bad" /><span>Product provider “{p.provider}” {p.ok ? "returned partial results" : "is unavailable"}: {p.message}. {p.ok ? "" : "Showing built-in catalog results only."}</span>
        </div>
      ))}
      {res.notes.length > 0 && (
        <div role="status" className="rounded-xl border border-amber-500/30 bg-amber-500/5 p-4 text-sm text-slate-200">
          <ul className="space-y-1">{res.notes.map((n) => <li key={n} className="flex gap-2"><AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-warn" />{n}</li>)}</ul>
        </div>
      )}
    </div>
  );
}
