import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { beforeEach, describe, expect, it, vi } from "vitest";

const calls: { path: string; method?: string; body?: unknown }[] = [];
let parseResponse: unknown;
vi.mock("@/lib/api", () => ({
  ApiError: class extends Error {},
  auth: { get: () => "t", set: () => {}, clear: () => {} },
  api: vi.fn(async (path: string, init: { method?: string; body?: unknown } = {}) => {
    calls.push({ path, ...init });
    if (path === "/api/policies" && !init.method) return [{ id: "p1", name: "My policy", raw_text: "", currency: "INR", max_budget: "75000.00", approval_threshold: "25000.00", approved_merchants_only: true, duplicate_purchase_check: true, auto_approve_enabled: true, approval_ttl_minutes: 30, is_active: true, approved_merchants: ["ElectroHub"], created_at: "2026-01-01T00:00:00" }];
    if (path === "/api/merchants") return { approved_merchants: ["ElectroHub"] };
    if (path === "/api/policies/parse") return parseResponse;
    return {};
  }),
}));

import Policies from "@/app/(app)/policies/page";

beforeEach(() => { calls.length = 0; });

describe("Policy Builder", () => {
  it("when Gemini failed: labels the fallback honestly, lets the user edit values, and saves the EDITED values", async () => {
    parseResponse = { draft: { currency: "INR", max_budget: "65000", approval_threshold: "25000", approved_merchants_only: true, duplicate_purchase_check: true, approved_merchants: [], source: "heuristic_fallback" },
      source: "heuristic_fallback", model: null, fallback_reason: "model_not_found", fallback_message: "Model 'x' was not found. Used the built-in rule-based parser instead." };
    render(<Policies />);
    fireEvent.click(await screen.findByRole("button", { name: /Interpret policy/ }));
    expect(await screen.findByText(/Rule-based parser · Gemini model not found/)).toBeInTheDocument();
    expect(screen.queryByText(/Generated by Gemini/)).toBeNull();
    const budget = screen.getByLabelText(/Maximum budget/) as HTMLInputElement;
    expect(budget.value).toBe("65000");
    fireEvent.change(budget, { target: { value: "60000" } });                 // user corrects the value before saving
    fireEvent.click(screen.getByRole("button", { name: "Confirm and save" }));
    await waitFor(() => expect(calls.some((c) => c.path === "/api/policies" && c.method === "POST")).toBe(true));
    const save = calls.find((c) => c.path === "/api/policies" && c.method === "POST")!.body as Record<string, unknown>;
    expect(save.max_budget).toBe("60000");
  });

  it("blocks saving a threshold above the budget", async () => {
    parseResponse = { draft: { currency: "INR", max_budget: "1000", approval_threshold: "500", approved_merchants_only: true, duplicate_purchase_check: true, approved_merchants: [], source: "gemini" },
      source: "gemini", model: "gemini-3.8-flash", fallback_reason: null, fallback_message: null };
    render(<Policies />);
    fireEvent.click(await screen.findByRole("button", { name: /Interpret policy/ }));
    expect(await screen.findByText(/Generated by Gemini · gemini-3.8-flash/)).toBeInTheDocument();
    fireEvent.change(screen.getByLabelText(/Ask me above/), { target: { value: "5000" } });
    expect(screen.getByRole("alert")).toHaveTextContent(/cannot be higher/);
    expect(screen.getByRole("button", { name: "Confirm and save" })).toBeDisabled();
  });

  it("edits a saved policy via PATCH", async () => {
    render(<Policies />);
    fireEvent.click(await screen.findByRole("button", { name: /Edit/ }));
    const budget = await screen.findByLabelText(/Maximum budget/);
    fireEvent.change(budget, { target: { value: "90000" } });
    fireEvent.click(screen.getByRole("button", { name: "Save changes" }));
    await waitFor(() => expect(calls.some((c) => c.method === "PATCH")).toBe(true));
    const patch = calls.find((c) => c.method === "PATCH")!;
    expect(patch.path).toBe("/api/policies/p1");
    expect((patch.body as Record<string, unknown>).max_budget).toBe("90000");
  });
});
