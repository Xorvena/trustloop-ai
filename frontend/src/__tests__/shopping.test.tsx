import { fireEvent, render, screen } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { ProductCard } from "@/components/shopping/ProductCard";
import { ProductImage } from "@/components/shopping/ProductImage";
import { SearchSummary, SourceBadge } from "@/components/shopping/SearchSummary";
import type { Product, SearchResponse, SearchResult } from "@/types";

const product = (over: Partial<Product> = {}): Product => ({
  id: "p1", sku: "LT-ASUS-VB15", name: "ASUS Vivobook 15 X1504", brand: "ASUS", model: "Vivobook 15 X1504", merchant: "ElectroHub", category: "electronics",
  product_type: "laptop", price: "46990.00", currency: "INR", description: "", specs: { ram_gb: 16, storage_gb: 512 }, availability: "in_stock",
  image_url: "/catalog/laptop.svg", image_source: "illustration", source: "curated_static_catalog", ...over,
});
const result = (over: Partial<SearchResult> = {}): SearchResult => ({
  product: product(), kind: "alternative", score: 60, merchant_approved: true, unconfirmed_terms: [], meets_requirements: false, relation: "same_line", suspicious_description: false, injection_flags: [],
  unmet: ["Model: VivobookX16 — different model in the same line ('Vivobook 15 X1504')"],
  checks: [{ key: "brand", label: "Brand: ASUS", met: true, detail: "brand matches" }, { key: "model", label: "Model: VivobookX16", met: false, detail: "different model" }], ...over,
});
const response = (over: Partial<SearchResponse> = {}): SearchResponse => ({
  status: "no_exact_match", requirements: {}, interpreted_as: ["brand: ASUS", "model: VivobookX16"], unverifiable_terms: [], notes: ["'ASUS VivobookX16' isn't in the catalog."],
  summary: "No exact match. 'ASUS VivobookX16' isn't in the catalog.", summary_source: "template", summary_model: null, summary_used_fallback_model: false, summary_fallback_reason: "model_not_found",
  summary_fallback_message: "Gemini summary unavailable (Model 'x' was not found); showing a built-in template summary instead.", intent_source: "heuristic", intent_model: null, intent_used_fallback_model: false,
  intent_fallback_reason: "model_not_found", intent_fallback_message: "x", intent_notes: [], gemini_status: null, provider_status: [], catalog_notice: "Curated demo catalog: prices, specs and availability are illustrative, not live retailer data.",
  matches: [], alternatives: [result()], results: [result()], ...over,
});

describe("ProductImage", () => {
  it("renders the image with an Illustration tag", () => {
    render(<ProductImage src="/catalog/laptop.svg" source="illustration" name="Laptop" />);
    expect(screen.getByAltText("Laptop")).toHaveAttribute("src", "/catalog/laptop.svg");
    expect(screen.getByText("Illustration")).toBeInTheDocument();
  });
  it("falls back gracefully when there is no image URL", () => {
    render(<ProductImage src={null} name="Laptop" />);
    expect(screen.getByRole("img", { name: "No image available" })).toBeInTheDocument();
    expect(screen.queryByAltText("Laptop")).toBeNull();
  });
  it("falls back when the image fails to load", () => {
    render(<ProductImage src="/missing.png" name="Laptop" />);
    fireEvent.error(screen.getByAltText("Laptop"));
    expect(screen.getByRole("img", { name: "No image available" })).toBeInTheDocument();
  });
  it("does not label licensed photos as illustrations", () => {
    render(<ProductImage src="/catalog/x.jpg" source="licensed_photo" name="X" />);
    expect(screen.queryByText("Illustration")).toBeNull();
  });
});

describe("summary provenance", () => {
  it("labels a Gemini summary with its model", () => {
    render(<SourceBadge source="gemini" model="gemini-3.8-flash" reason={null} />);
    expect(screen.getByText(/Generated by Gemini · gemini-3.8-flash/)).toBeInTheDocument();
  });
  it("labels a template summary as NOT AI and shows the failure reason", () => {
    render(<SearchSummary res={response()} />);
    expect(screen.getByText(/Template summary \(not AI\) · Gemini model not found/)).toBeInTheDocument();
    expect(screen.queryByText(/Generated by Gemini/)).toBeNull();
    expect(screen.getByText(/showing a built-in template summary instead/)).toBeInTheDocument();
  });
  it("shows catalog notes and unverifiable terms", () => {
    render(<SearchSummary res={response({ unverifiable_terms: ["gaming"], summary_fallback_reason: "not_configured" })} />);
    expect(screen.getAllByText(/isn't in the catalog/).length).toBeGreaterThan(0);
    expect(screen.getByText(/Could not verify against catalog data: gaming/)).toBeInTheDocument();
  });
});

describe("providers, merchants and honesty", () => {
  it("labels provider photos as demo photos, not retailer images", () => {
    render(<ProductImage src="https://cdn.dummyjson.com/x.webp" source="provider_photo" name="X" />);
    expect(screen.getByText("Demo photo")).toBeInTheDocument();
  });
  it("shows an unavailable provider clearly and says only built-in results are shown", () => {
    render(<SearchSummary res={response({ provider_status: [{ provider: "dummyjson", ok: false, count: 0, code: "network_error", message: "Could not reach the product provider (ConnectError)." }] })} />);
    expect(screen.getByText(/is unavailable: Could not reach the product provider/)).toBeInTheDocument();
    expect(screen.getByText(/Showing built-in catalog results only/)).toBeInTheDocument();
  });
  it("notes a successful provider search as demo data", () => {
    render(<SearchSummary res={response({ provider_status: [{ provider: "dummyjson", ok: true, count: 12, code: null, message: null }] })} />);
    expect(screen.getByText(/Also searched demo provider “dummyjson” \(12 products\)/)).toBeInTheDocument();
  });
  it("offers one-click approval when the merchant is not on the allowlist", () => {
    const fn = vi.fn();
    render(<ProductCard r={result({ merchant_approved: false, product: product({ merchant: "DummyJSON Demo Store", source: "provider:dummyjson" }) })} busy={false} onPropose={() => {}} onApproveMerchant={fn} />);
    expect(screen.getByText(/will need your review/)).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: /Add DummyJSON Demo Store to approved merchants/ }));
    expect(fn).toHaveBeenCalledWith("DummyJSON Demo Store");
    expect(screen.getByText("Demo provider")).toBeInTheDocument();
  });
  it("lists descriptive terms that are not confirmed in the product details", () => {
    render(<ProductCard r={result({ kind: "match", meets_requirements: true, unmet: [], unconfirmed_terms: ["armrests", "adjustable"] })} busy={false} onPropose={() => {}} />);
    expect(screen.getByText(/Not confirmed in product details: armrests, adjustable/)).toBeInTheDocument();
  });
});

describe("fallback model explanation", () => {
  it("explains why the fallback model answered, using the primary's last failure", () => {
    render(<SearchSummary res={response({ summary_source: "gemini", summary_model: "gemini-3.5-flash-lite", summary_used_fallback_model: true, summary_fallback_reason: null,
      gemini_status: { primary_model: "gemini-3.8-flash", fallback_model: "gemini-3.5-flash-lite", primary_cooling_down_seconds: 90, primary_last_failure: { code: "upstream_error", message: "Gemini service error (HTTP 504).", seconds_ago: 5 } } })} />);
    expect(screen.getByText(/is not answering/)).toBeInTheDocument();
    expect(screen.getByText(/upstream_error: Gemini service error \(HTTP 504\)/)).toBeInTheDocument();
    expect(screen.getByText(/\/api\/health\/gemini\/probe/)).toBeInTheDocument();
  });
  it("pluralises the provider count", () => {
    render(<SearchSummary res={response({ provider_status: [{ provider: "dummyjson", ok: true, count: 1, code: null, message: null }] })} />);
    expect(screen.getByText(/\(1 product\)/)).toBeInTheDocument();
  });
});

describe("fallback model honesty", () => {
  it("says when the fallback model produced the text", () => {
    render(<SourceBadge source="gemini" model="gemini-3.5-flash-lite" reason={null} fallbackModel />);
    expect(screen.getByText(/Generated by Gemini · gemini-3.5-flash-lite \(fallback model\)/)).toBeInTheDocument();
  });
  it("explains a skipped call during an outage", () => {
    render(<SourceBadge source="template" model={null} reason="recently_unavailable" />);
    expect(screen.getByText(/Gemini was unavailable moments ago/)).toBeInTheDocument();
  });
});

describe("ProductCard", () => {
  it("lists what an alternative does not satisfy", () => {
    render(<ProductCard r={result()} busy={false} onPropose={() => {}} />);
    expect(screen.getByText("Alternative")).toBeInTheDocument();
    expect(screen.getByText("Does not satisfy:")).toBeInTheDocument();
    expect(screen.getByText(/different model in the same line/)).toBeInTheDocument();
  });
  it("marks matches and calls onPropose", () => {
    const fn = vi.fn();
    render(<ProductCard r={result({ kind: "match", meets_requirements: true, unmet: [] })} top busy={false} onPropose={fn} />);
    expect(screen.getByText("Top match")).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "Create purchase proposal" }));
    expect(fn).toHaveBeenCalled();
  });
  it("disables out-of-stock products", () => {
    render(<ProductCard r={result({ product: product({ availability: "out_of_stock" }) })} busy={false} onPropose={() => {}} />);
    expect(screen.getByRole("button", { name: "Out of stock" })).toBeDisabled();
  });
  it("shows the placeholder for a product without an image", () => {
    render(<ProductCard r={result({ product: product({ image_url: null, image_source: null }) })} busy={false} onPropose={() => {}} />);
    expect(screen.getByRole("img", { name: "No image available" })).toBeInTheDocument();
  });
});
